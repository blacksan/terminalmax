import org.gradle.api.JavaVersion
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.plugins.JavaPluginExtension
import org.gradle.kotlin.dsl.configure
import org.gradle.kotlin.dsl.withType
import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import org.jetbrains.kotlin.gradle.dsl.KotlinMultiplatformExtension
import org.jetbrains.kotlin.gradle.tasks.KotlinJvmCompile

/**
 * KMP library with Android (AGP 9 `com.android.kotlin.multiplatform.library`) and desktop JVM targets.
 *
 * The Android block (`kotlin { android { namespace/compileSdk/minSdk } }`) is intentionally
 * configured in each module's build file, where the typed DSL accessor is generated by Gradle,
 * so this plugin does not depend on the exact AGP DSL interface name.
 */
class KmpLibraryConventionPlugin : Plugin<Project> {
    override fun apply(target: Project) {
        with(target) {
            pluginManager.apply("org.jetbrains.kotlin.multiplatform")
            pluginManager.apply("com.android.kotlin.multiplatform.library")

            extensions.configure<KotlinMultiplatformExtension> {
                // Target name "desktop" => source sets desktopMain/desktopTest, task desktopTest.
                jvm("desktop")
                sourceSets.getByName("commonTest").dependencies {
                    implementation(libs.findLibrary("kotlin-test").get())
                }
            }

            // JVM 17 bytecode for every Kotlin/JVM compilation (desktop + android) without a toolchain.
            tasks.withType<KotlinJvmCompile>().configureEach {
                compilerOptions.jvmTarget.set(JvmTarget.JVM_17)
            }

            // Print full failure details on the console: CI logs are the only place test output is read.
            tasks.withType<org.gradle.api.tasks.testing.Test>().configureEach {
                testLogging {
                    events("failed")
                    exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
                    showCauses = true
                    showStackTraces = true
                }
            }

            // Keep javac and the published org.gradle.jvm.version attribute at 17 so :desktopApp (Java 17)
            // can consume the desktop variant.
            pluginManager.withPlugin("java-base") {
                extensions.configure<JavaPluginExtension> {
                    sourceCompatibility = JavaVersion.VERSION_17
                    targetCompatibility = JavaVersion.VERSION_17
                }
            }
        }
    }
}
